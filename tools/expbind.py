#!/usr/bin/env python3
"""Generate BIOS bridge bindings from the assembled EXP CCP symbol map."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
symbols = {n: int(v, 16) for v, n in re.findall(r"\b([0-9A-F]{4})\s+([A-Z][A-Z0-9]*)", (root / "ccpexp.sym").read_text())}
names = {"ccp_hook": "CMDHOOK", "ccp_file": "WKFCB", "ccp_open": "OPENW",
         "ccp_cmd": "TRNCMO", "ccp_error": "COMERR", "ccp_exit": "CCPLOP",
         "ccp_restore": "SLCRDR", "ccp_parse": "GTFNAM", "ccp_parse2": "GTFNAS",
         "ccp_drive": "TDRVNU", "ccp_tail": "PNTCMD", "ccp_buffer": "CMBUFF", "ccp_stack": "STACK"}
text = "; Generated by tools/expbind.py; EXP CCP offsets, not MBC offsets.\n"
memory = {"ccp_hook", "ccp_file", "ccp_drive", "ccp_tail", "ccp_buffer", "ccp_stack"}
for alias, name in names.items():
    text += f"{'dseg' if alias in memory else 'cseg'}\n org 0{symbols[name]:04X}h\n{alias}{" rb 0" if alias in memory else ":"}\n"
(root / "cppexp.equ").write_text(text)
