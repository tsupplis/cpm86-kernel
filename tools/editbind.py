#!/usr/bin/env python3
"""Bind the EXP editor to existing BDOS console primitives and state."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
symbols = {n: int(v, 16) for v, n in re.findall(r"\b([0-9A-F]{4})\s+([A-Z][A-Z0-9]*)", (root / "bdosexp.sym").read_text())}
code = {"le_original": "RDCNBF", "le_abort": "CONSTA", "le_diskreset": "MRSDSY", "le_getchar": "CONINC", "le_putvisible": "CONOTC", "le_putraw": "BCONOT"}
words = {"le_arg": "INPARA", "le_segment": "INDSEG"}
bytes_ = {"le_column": "PCARIG", "le_prompt": "PPROMP", "le_list": "LSTTGL"}
text = "; Generated by tools/editbind.py; EXP BDOS console contract.\n"
for names, directive, suffix in ((code, "cseg", ":"), (words, "dseg", " rw 0"), (bytes_, "dseg", " rb 0")):
    for alias, name in names.items():
        text += f"{directive}\n org 0{symbols[name]:04X}h\n{alias}{suffix}\n"
(root / "bdosbind.equ").write_text(text)
